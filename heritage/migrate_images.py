#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
商品图片迁移脚本
1. 将 springboot/files/bussiness/shop_product/ 下的图片复制到 vue3/public/image/
2. 生成更新数据库的 SQL 语句
3. 命名规则: {businessId}_{businessField}_{fileId}.{ext}
"""

import os
import shutil
import sys
import csv
import io

# 修复 Windows GBK 输出问题
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8', errors='replace')

# ========== 配置 ==========
BASE_DIR = r"d:\SOFTWARE\test\3_feiyi"
SOURCE_DIR = os.path.join(BASE_DIR, "springboot", "files", "bussiness", "shop_product")
TARGET_DIR = os.path.join(BASE_DIR, "vue3", "public", "image")
TSV_FILE = os.path.join(BASE_DIR, "temp_migration_data.tsv")
SQL_FILE = os.path.join(BASE_DIR, "update_image_paths.sql")
LOG_FILE = os.path.join(BASE_DIR, "migrate_images_log.txt")

# ========== 确保目标目录存在 ==========
os.makedirs(TARGET_DIR, exist_ok=True)

# ========== 读取数据 ==========
records = []
# MySQL CLI 在 Windows 中文环境输出编码为 GBK
with open(TSV_FILE, "r", encoding="latin-1") as f:
    reader = csv.DictReader(f, delimiter="\t")
    for row in reader:
        records.append(row)

print(f"Total records read: {len(records)}")
log_lines = []
sql_lines = ["-- Product image path migration SQL", "-- Auto-generated by migration script", ""]

success_count = 0
skip_count = 0
error_count = 0

for i, rec in enumerate(records):
    file_id = rec["id"].strip()
    original_name = rec["original_name"].strip()
    file_path = rec["file_path"].strip()
    business_id = rec["business_id"].strip()
    business_field = rec["business_field"].strip()

    # 提取源文件名 (file_path 的最后一段)
    src_filename = os.path.basename(file_path)
    src_full_path = os.path.join(SOURCE_DIR, src_filename)

    # 确定扩展名
    _, ext = os.path.splitext(src_filename)
    if not ext:
        _, ext = os.path.splitext(original_name)
    if not ext:
        ext = ".jpg"  # 默认

    # 新文件名: {businessId}_{businessField}_{fileId}.{ext}
    new_filename = f"{business_id}_{business_field}_{file_id}{ext}"
    new_full_path = os.path.join(TARGET_DIR, new_filename)

    # 新的数据库路径（相对路径，Vue3 可直接访问）
    new_db_path = f"/image/{new_filename}"

    msg = f"[{i+1}/{len(records)}] ID={file_id} | {business_id} | {business_field} | {src_filename} -> {new_filename}"

    # 检查源文件是否存在
    if not os.path.exists(src_full_path):
        msg += f" | [SKIP] Source file not found: {src_full_path}"
        print(msg)
        log_lines.append(msg)
        skip_count += 1
        continue

    # 复制文件
    try:
        shutil.copy2(src_full_path, new_full_path)
        msg += " | [OK] Copied successfully"
        success_count += 1

        # 生成 SQL
        sql = f"UPDATE sys_file_info SET file_path = '{new_db_path}' WHERE id = {file_id};"
        sql_lines.append(f"-- {business_id} / {business_field}")
        sql_lines.append(sql)
        sql_lines.append("")

    except Exception as e:
        msg += f" | [ERROR] Copy failed: {e}"
        error_count += 1

    print(msg)
    log_lines.append(msg)

# ========== 生成汇总 ==========
summary = f"""
========================================
Migration Summary
========================================
Total records: {len(records)}
Success: {success_count}
Skipped (source file missing): {skip_count}
Errors: {error_count}
========================================
"""
print(summary)
log_lines.append(summary)

# ========== 写入 SQL 文件 ==========
sql_lines.append(f"-- Total {success_count} UPDATE statements")
sql_lines.append("-- Execute this SQL file to update database paths")
with open(SQL_FILE, "w", encoding="utf-8") as f:
    f.write("\n".join(sql_lines))

# ========== 写入日志文件 ==========
with open(LOG_FILE, "w", encoding="utf-8") as f:
    f.write("\n".join(log_lines))

print(f"SQL file generated: {SQL_FILE}")
print(f"Log file generated: {LOG_FILE}")
print()
print("To update the database, run:")
print(f'  mysql -uroot -pmysql123456 -h127.0.0.1 -P3306 heritage < "{SQL_FILE}"')
